if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python subset_emoji.py input.ttf output.ttf")
        sys.exit(1)

    try:
        from fontTools.subset import Options, Subsetter
        from fontTools.ttLib import TTFont
    except ImportError:
        print("Installing fonttools...")
        import subprocess
        subprocess.check_call([sys.executable, "-m", "pip", "install", "fonttools", "brotli"])
        from fontTools.subset import Options, Subsetter
        from fontTools.ttLib import TTFont

    input_path = sys.argv[1]
    output_path = sys.argv[2]

    print(f"Loading {input_path}...")
    font = TTFont(input_path)

    codepoints = get_codepoints()
    print(f"Subsetting to {len(codepoints)} codepoints...")

    options = Options()
    options.layout_features = ['*']
    options.hinting = False
    options.desubroutinize = True

    subsetter = Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)

    print(f"Saving {output_path}...")
    font.save(output_path)

    import os
    in_size = os.path.getsize(input_path) / (1024 * 1024)
    out_size = os.path.getsize(output_path) / (1024 * 1024)
    print(f"Done! {in_size:.1f}MB -> {out_size:.1f}MB ({100 - (out_size/in_size)*100:.0f}% reduction)")
